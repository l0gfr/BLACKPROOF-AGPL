import { readFile, mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";

import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { build } from "esbuild";

const checkOnly = process.argv.includes("--check");
const localBackupManifestSchema = JSON.parse(await readFile(resolve("apps/web/src/schemas/local-backup-manifest-v2.schema.json"), "utf8"));
const publicDeliveryStatusSchema = JSON.parse(await readFile(resolve("packages/verifier/schemas/status-v1.schema.json"), "utf8"));
const frozenPublicSchemas = [
  {
    label: "ProofPack v1",
    schemaPath: resolve("packages/core/schemas/proofpack-v1.schema.json"),
    expectedSha256: "c6c1d162abc0aada780df954338989999596461727e770d475d81ba2a3813d26",
    outputPath: resolve("packages/core/src/generated/proofpack-v1-validator.js"),
    sourcefile: "proofpack-v1-validator.generated.js",
  },
  {
    label: "ProofPack v2",
    schemaPath: resolve("packages/core/schemas/proofpack-v2.schema.json"),
    expectedSha256: "4edb89244670fca5624bda95d93e617bfd34a92c9981bfba5ace1d6f83f4bdb2",
    outputPath: resolve("packages/core/src/generated/proofpack-v2-validator.js"),
    sourcefile: "proofpack-v2-validator.generated.js",
  },
  {
    label: "ProofPack v3",
    schemaPath: resolve("packages/core/schemas/proofpack-v3.schema.json"),
    expectedSha256: "7bd8cfb8bcfb5cb1cbd5ddf8f9b157aa1c6dc71503916239a76b80b8691b2c6c",
    outputPath: resolve("packages/core/src/generated/proofpack-validator.js"),
    sourcefile: "proofpack-validator.generated.js",
  },
  {
    label: "ProofPack Delivery v4",
    schemaPath: resolve("packages/core/schemas/proofpack-delivery-v4.schema.json"),
    expectedSha256: "08860d15b4aa5a683ad8b7923d0421929a2f464d559243f2cdff76b7534eb73c",
    outputPath: resolve("packages/core/src/generated/delivery-v4-validator.js"),
    sourcefile: "delivery-v4-validator.generated.js",
  },
  {
    label: "ProofPack Delivery v5",
    schemaPath: resolve("packages/core/schemas/proofpack-delivery-v5.schema.json"),
    expectedSha256: "f5bd12f5e227748aaa7e8dce1cf5701e0ed5f23e9d079d8b37c4d77ad31c6732",
    outputPath: resolve("packages/core/src/generated/delivery-validator.js"),
    sourcefile: "delivery-validator.generated.js",
  },
];

for (const spec of frozenPublicSchemas) {
  const bytes = await readFile(spec.schemaPath);
  const actualSha256 = createHash("sha256").update(bytes).digest("hex");
  if (actualSha256 !== spec.expectedSha256) {
    console.error(`Frozen ${spec.label} schema changed: expected ${spec.expectedSha256}, got ${actualSha256}. Publish a new schema version instead.`);
    process.exit(1);
  }
  spec.schema = JSON.parse(bytes.toString("utf8"));
}

const verifierValidators = frozenPublicSchemas
  .filter((spec) => spec.label === "ProofPack Delivery v4" || spec.label === "ProofPack Delivery v5")
  .map((spec) => ({
    ...spec,
    label: `Standalone verifier ${spec.label}`,
    outputPath: resolve(`packages/verifier/src/generated/${spec.label.endsWith("v4") ? "delivery-v4-validator.js" : "delivery-v5-validator.js"}`),
    sourcefile: `standalone-${spec.sourcefile}`,
  }));

const validators = [
  ...frozenPublicSchemas,
  ...verifierValidators,
  {
    label: "Standalone verifier public Delivery status v1",
    schema: publicDeliveryStatusSchema,
    outputPath: resolve("packages/verifier/src/generated/status-v1-validator.js"),
    sourcefile: "standalone-status-v1-validator.generated.js",
  },
  {
    label: "Local Backup Manifest V2",
    schema: localBackupManifestSchema,
    outputPath: resolve("apps/web/src/lib/generated/local-backup-manifest-v2-validator.js"),
    sourcefile: "local-backup-manifest-v2-validator.generated.js",
  },
];

async function generateValidator(spec) {
  const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    code: { source: true, esm: true, lines: true },
  });
  addFormats(ajv);
  const validate = ajv.compile(spec.schema);
  const bundled = await build({
    bundle: true,
    format: "esm",
    legalComments: "none",
    platform: "browser",
    target: "es2022",
    write: false,
    stdin: {
      contents: standaloneCode(ajv, validate),
      loader: "js",
      resolveDir: process.cwd(),
      sourcefile: spec.sourcefile,
    },
  });
  return [
    "// Generated by scripts/generate-proofpack-validator.mjs. Do not edit manually.",
    "// Ajv standalone validator: no eval or dynamic code generation at runtime.",
    bundled.outputFiles[0].text,
  ].join("\n");
}

for (const spec of validators) {
  const generated = await generateValidator(spec);
  if (checkOnly) {
    let current = "";
    try {
      current = await readFile(spec.outputPath, "utf8");
    } catch {
      // Report the same actionable drift error for a missing artifact.
    }
    if (current !== generated) {
      console.error(`Generated ${spec.label} validator is stale. Run: pnpm schema:generate`);
      process.exit(1);
    }
    console.log(`Generated ${spec.label} validator matches the canonical schema.`);
  } else {
    await mkdir(dirname(spec.outputPath), { recursive: true });
    await writeFile(spec.outputPath, generated, "utf8");
    console.log(`Generated standalone ${spec.label} validator: ${spec.outputPath}`);
  }
}
